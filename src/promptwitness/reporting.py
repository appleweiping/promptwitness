def _change_to_dict(change: Change) -> dict[str, Any]:
    return {
        "kind": change.kind.value,
        "path": change.path,
        "severity": change.severity.value,
        "summary": change.summary,
        "before": _json_value(change.before),
        "after": _json_value(change.after),
        "unified_diff": list(change.unified_diff),
    }


def _finding_to_dict(finding: Finding) -> dict[str, str]:
    return {
        "code": finding.code.value,
        "path": finding.path,
        "severity": finding.severity.value,
        "message": finding.message,
    }


def _render_diff_markdown(report: DiffReport) -> str:
    state = "compatible" if report.compatible else "breaking"
    lines = [
        "# PromptWitness diff",
        "",
        f"`{_md(report.before_id)}` → `{_md(report.after_id)}` · **{state}** · "
        f"{len(report.changes)} change(s), {report.breaking_count} breaking",
        "",
        "| Severity | Kind | Path | Summary |",
        "|---|---|---|---|",
    ]
    for change in report.changes:
        lines.append(
            f"| {change.severity.value} | `{change.kind.value}` | `{_md(change.path)}` | "
            f"{_md(change.summary)} |"
        )
    if not report.changes:
        lines.append("| — | — | — | No changes |")
    diffs = [change for change in report.changes if change.unified_diff]
    for change in diffs:
        fence = _markdown_fence(change.unified_diff)
        lines.extend(
            [
                "",
                f"## `{_md(change.path)}`",
                "",
                f"{fence}diff",
                *change.unified_diff,
                fence,
            ]
        )
    return "\n".join(lines) + "\n"


def _render_validation_markdown(report: ValidationReport) -> str:
    state = "valid" if report.valid else "invalid"
    lines = [
        "# PromptWitness validation",
        "",
        f"`{_md(report.prompt_id)}` · **{state}** · {len(report.findings)} finding(s), "
        f"{report.breaking_count} breaking",
        "",
        "| Severity | Code | Path | Message |",
        "|---|---|---|---|",
    ]
    for finding in report.findings:
        lines.append(
            f"| {finding.severity.value} | `{finding.code.value}` | `{_md(finding.path)}` | "
            f"{_md(finding.message)} |"
        )
    if not report.findings:
        lines.append("| — | — | — | No findings |")
    return "\n".join(lines) + "\n"


def _html_content(
    report: DiffReport | ValidationReport,
) -> tuple[str, str, str, str, list[str]]:
    rows: list[str] = []
    if isinstance(report, DiffReport):
        title = "PromptWitness diff"
        subtitle = (
            f"{report.before_id} → {report.after_id} · {len(report.changes)} change(s) · "
            f"{report.breaking_count} breaking"
        )
        status_class, status_text = (
            ("pass", "Compatible") if report.compatible else ("fail", "Breaking changes")
        )
        for change in report.changes:
            rows.append(
                _html_row(
                    change.severity.value,
                    change.kind.value,
                    change.path,
                    change.summary,
                )
            )
    else:
        title = "PromptWitness validation"
        subtitle = (
            f"{report.prompt_id} · {len(report.findings)} finding(s) · "
            f"{report.breaking_count} breaking"
        )
        status_class, status_text = ("pass", "Valid") if report.valid else ("fail", "Invalid")
        for finding in report.findings:
            rows.append(
                _html_row(
                    finding.severity.value,
                    finding.code.value,
                    finding.path,
                    finding.message,
                )
            )
    return title, subtitle, status_class, status_text, rows


def _html_row(severity: str, kind: str, path: str, summary: str) -> str:
    return (
        f'<tr><td><span class="severity {severity}">{escape(severity)}</span></td>'
        f"<td><code>{escape(kind)}</code></td><td><code>{escape(path)}</code></td>"
        f"<td>{escape(summary)}</td></tr>"
    )


def _md(value: str) -> str:
    return (
        value.replace("&", "&amp;")
        .replace("|", "&#124;")
        .replace("`", "&#96;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("\r", " ")
        .replace("\n", " ")
    )


def _markdown_fence(lines: tuple[str, ...]) -> str:
    longest = 0
    for line in lines:
        longest = max(longest, *(len(match) for match in re.findall(r"`+", line)), 0)
    return "`" * max(3, longest + 1)


def _json_value(value: Any) -> Any:
    if isinstance(value, Mapping):
        return {key: _json_value(nested) for key, nested in value.items()}
    if isinstance(value, tuple):
        return [_json_value(item) for item in value]
    return value
