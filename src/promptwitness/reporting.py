"""Machine-readable, Markdown, and standalone HTML reports."""

from __future__ import annotations

import json
import re
from collections.abc import Mapping
from html import escape
from typing import Any

from .models import Change, DiffReport, Finding, ValidationReport

REPORT_SCHEMA_VERSION = 1


def diff_to_dict(report: DiffReport) -> dict[str, Any]:
    """Convert a diff report to the stable versioned wire shape."""

    return {
        "schema_version": REPORT_SCHEMA_VERSION,
        "report_type": "diff",
        "before_id": report.before_id,
        "after_id": report.after_id,
        "compatible": report.compatible,
        "summary": {
            "changes": len(report.changes),
            "breaking": report.breaking_count,
            "warnings": report.warning_count,
        },
        "changes": [_change_to_dict(change) for change in report.changes],
    }


def validation_to_dict(report: ValidationReport) -> dict[str, Any]:
    """Convert a validation report to the stable versioned wire shape."""

    return {
        "schema_version": REPORT_SCHEMA_VERSION,
        "report_type": "validation",
        "prompt_id": report.prompt_id,
        "valid": report.valid,
        "summary": {
            "findings": len(report.findings),
            "breaking": report.breaking_count,
            "warnings": report.warning_count,
        },
        "findings": [_finding_to_dict(finding) for finding in report.findings],
    }


def render_json(report: DiffReport | ValidationReport) -> str:
    """Render a report as deterministic UTF-8-friendly JSON."""

    payload = diff_to_dict(report) if isinstance(report, DiffReport) else validation_to_dict(report)
    return json.dumps(payload, indent=2, ensure_ascii=False, sort_keys=True, allow_nan=False) + "\n"


def render_markdown(report: DiffReport | ValidationReport) -> str:
    """Render a compact human review document."""

    if isinstance(report, DiffReport):
        return _render_diff_markdown(report)
    return _render_validation_markdown(report)


